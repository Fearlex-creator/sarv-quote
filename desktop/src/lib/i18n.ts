export function translate(
  text: string,
  locale: Locale,
  values?: MessageValues,
): string {
  const message =
    locale === "fa" ? (messages[text] ?? persian[text] ?? text) : text;
  return message.replace(/\{(\w+)\}/g, (placeholder, key: string) => {
    const value = values?.[key];
    if (value === undefined) return placeholder;
    const rendered =
      typeof value === "number"
        ? new Intl.NumberFormat(locale === "fa" ? "fa-IR" : "en-US", {
            useGrouping: false,
          }).format(value)
        : value;
    return locale === "fa" ? isolate(rendered) : rendered;
  });
}
export function useTranslation() {
  const locale = useContext(I18nContext);
  return useCallback(
    (text: string, values?: MessageValues) => translate(text, locale, values),
    [locale],
  );
}
export function initialLocale(): Locale {
  const saved = localStorage.getItem("sarv.language");
  if (saved === "en" || saved === "fa") return saved;
  return navigator.language.toLowerCase().startsWith("fa") ? "fa" : "en";
}
// Keep record names and references independent of surrounding RTL text.
export function isolate(value: string) {
  return `\u2068${value}\u2069`;
}
